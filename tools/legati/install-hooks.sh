#!/usr/bin/env bash
# Wire the legati session-start brief, the per-turn inbox check and the Observatory capture into a harness
# on THIS machine. Idempotent.
#   bash tools/legati/install-hooks.sh codex    -> .codex/hooks.json + .codex/config.toml (gitignored, per machine),
#                                                 and trusts the repo in ~/.codex/config.toml so they load
#   bash tools/legati/install-hooks.sh claude   -> nothing to do: the tracked .claude/settings.json already carries
#                                                 the hooks (with $CLAUDE_PROJECT_DIR paths); prints a check instead
# Hook wiring is per-machine scaffolding; the durable rule is legati/README.md.
set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
case "${1:-}" in
  claude)
    if grep -q "tools/legati/session-start.sh" "$REPO/.claude/settings.json" 2>/dev/null; then
      echo "[install-hooks] claude: hooks are in the tracked .claude/settings.json; nothing to install. Claude Code asks once to trust the project."
    else
      echo "[install-hooks] claude: .claude/settings.json has no legati hooks; restore it from git (git checkout -- .claude/settings.json)"; exit 1
    fi
    ;;
  codex)
    command -v codex >/dev/null || echo "[install-hooks] codex: WARNING the codex command is not on PATH (install it first; then run codex login)"
    mkdir -p "$REPO/.codex"
    OBS="python3 $REPO/engineering-projects/legati-observatory/adapters/codex/hook-handler.py"
    cat > "$REPO/.codex/hooks.json" <<JSON
{
  "hooks": {
    "SessionStart":     [{ "hooks": [{ "type": "command", "command": "bash $REPO/tools/legati/session-start.sh --codex-hook" },
                                     { "type": "command", "command": "$OBS" }] }],
    "UserPromptSubmit": [{ "hooks": [{ "type": "command", "command": "bash $REPO/tools/legati/turn-start.sh" },
                                     { "type": "command", "command": "$OBS" }] }],
    "PreToolUse":       [{ "matcher": ".*", "hooks": [{ "type": "command", "command": "$OBS" }] }],
    "PostToolUse":      [{ "matcher": ".*", "hooks": [{ "type": "command", "command": "$OBS" }] }],
    "SubagentStop":     [{ "hooks": [{ "type": "command", "command": "$OBS" }] }],
    "Stop":             [{ "hooks": [{ "type": "command", "command": "$OBS" }] }]
  }
}
JSON
    # Project-scoped Codex policy (loaded only once the repo is trusted). Workshop tools may need the network
    # (git push, Playwright, API calls); Codex's own memories stay off: the repo's memory/ is the only memory.
    cat > "$REPO/.codex/config.toml" <<TOML
# Generated by tools/legati/install-hooks.sh codex (per machine, gitignored). Loaded only when the repo is trusted.
approval_policy = "on-request"
sandbox_mode = "workspace-write"

[sandbox_workspace_write]
network_access = true

[features]
memories = false
TOML
    CFG="$HOME/.codex/config.toml"; mkdir -p "$HOME/.codex"; touch "$CFG"
    if grep -qF "[projects.\"$REPO\"]" "$CFG"; then
      echo "[install-hooks] codex: repo already trusted in $CFG"
    else
      printf '\n[projects."%s"]\ntrust_level = "trusted"\n' "$REPO" >> "$CFG"
      echo "[install-hooks] codex: trusted $REPO in $CFG"
    fi
    echo "[install-hooks] codex: wrote .codex/hooks.json + .codex/config.toml. Start Codex here once and approve the hooks with /hooks (trust is by hash; re-approve after editing them)."
    echo "[install-hooks] codex: if you move the repo, run this again (the hook paths are absolute)."
    ;;
  *) echo "usage: install-hooks.sh codex|claude"; exit 4;;
esac
