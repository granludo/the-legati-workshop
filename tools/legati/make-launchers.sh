#!/usr/bin/env bash
# Generate the root launch wrappers, one pair per legatus that has a boot file:
#   ./claude_<name>.sh  → legati/bin/legatus <name> claude-code
#   ./codex_<name>.sh   → legati/bin/legatus <name> codex
# Run it after you name, rename, add or retire a legatus (skills/start-here.md, step 1). Idempotent.
# Wrappers for a name that no longer has a boot file are moved to archive/launchers/ (archive, don't delete).
# Companion tabs: add the pair by hand, e.g. a claude_comms.sh that runs `legatus comms --with reviewer claude-code`.
set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$REPO"
made=()
for boot in characters/*/boot.md; do
  [ -f "$boot" ] || continue
  name="$(basename "$(dirname "$boot")")"
  for h in claude codex; do
    harness="$h"; label=Codex; [ "$h" = claude ] && { harness=claude-code; label="Claude Code"; }
    f="${h}_${name}.sh"
    cat > "$f" <<WRAP
#!/usr/bin/env bash
# $f: open $label in this tab as the legatus "$name". Generated by tools/legati/make-launchers.sh.
# Thin wrapper over legati/bin/legatus (sets LEGATUS_AGENT, names the tab, loads the boot file). Extra args go to the harness.
exec "\$(cd "\$(dirname "\${BASH_SOURCE[0]}")" && pwd)/legati/bin/legatus" $name $harness "\$@"
WRAP
    chmod +x "$f"; made+=("$f")
  done
done
for f in claude_*.sh codex_*.sh; do
  [ -f "$f" ] || continue
  name="${f#*_}"; name="${name%.sh}"
  if [ ! -f "characters/$name/boot.md" ]; then
    mkdir -p archive/launchers; git mv -f "$f" "archive/launchers/$f" 2>/dev/null || mv "$f" "archive/launchers/$f"
    echo "[make-launchers] archived $f (no characters/$name/boot.md)"
  fi
done
echo "[make-launchers] wrote ${made[*]}"
